function load(file, wx) {
  let page;
  vm.runInNewContext(fs.readFileSync(path.join(root, file), 'utf8'), {
    Page: (definition) => { page = definition; }, wx,
    require: (name) => {
      if (name.endsWith('/notices')) return notices;
      if (name.endsWith('/update-notice')) return { peekPendingAnnouncement: () => '', clearPendingAnnouncement() {} };
      return { withPageShare: (p) => p };
    }
  });
  page.setData = (data) => Object.assign(page.data, data);
  return page;
}
